const DICTS: Record<Locale, Dict> = { "zh-CN": ZH, "en-US": EN };

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (k: string, vars?: Record<string, string | number>) => string };
const I18nCtx = createContext<Ctx>({ locale: "zh-CN", setLocale: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("zh-CN");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("nz_locale") as Locale | null;
      if (saved === "zh-CN" || saved === "en-US") setLocaleState(saved);
    } catch {}
  }, []);
  const setLocale = (l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("nz_locale", l);
    } catch {}
  };
  const t = (k: string, vars?: Record<string, string | number>) => {
    let s = DICTS[locale][k] ?? DICTS["zh-CN"][k] ?? k;
    if (vars) for (const [key, val] of Object.entries(vars)) s = s.replace(`{${key}}`, String(val));
    return s;
  };
  return <I18nCtx.Provider value={{ locale, setLocale, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
